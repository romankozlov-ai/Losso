// Определяем категорию по названию
function detectCategory(name) {
  const lower = name.toLowerCase();
  for (const key of Object.keys(BENEFITS_DB)) {
    if (lower.includes(key.replace(/\\/g, ''))) return key;
  }
  return null;
}

// Anti-slop генерация текста
function generatePostText(product) {
  const category = detectCategory(product.name);
  const benefits = category ? BENEFITS_DB[category] : null;
  
  // Экранируем название
  const name = escapeTgMarkdown(product.name);
  
  // Эмодзи
  const categoryEmoji = {
    'сучкоріз': '🌳', 'секатор': '✂️', 'степлер': '📎',
    'ножиці': '✂️', 'підв\'яз': '📎', 'підвяз': '📎',
    'щеплен': '🔪', 'ножівка': '🪚', 'пила': '🪚',
    'лопат': '🥄', 'грабел': '🍂', 'грабл': '🍂', 'шланг': '🚿',
    'чохол': '🎒', 'рукавич': '🧤', 'кущоріз': '✂️',
    'висоторіз': '🌳', 'насос': '💧', 'розпилювач': '💦',
    'зрошувач': '🌀', 'дощувалка': '🌧️', 'стрічка': '📎',
    'кембрик': '📎', 'сапа': '⛏️', 'мотика': '🔧',
    'тачка': '🛒', 'оприскувач': '🧴', 'подрібнювач': '🪵'
  };
  
  let emoji = '🌿';
  for (const [key, em] of Object.entries(categoryEmoji)) {
    if (product.name.toLowerCase().includes(key.replace(/\\/g, ''))) {
      emoji = em;
      break;
    }
  }
  
  const parts = [`${emoji} *${name}*`, ''];
  
  // Добавляем пользу если нашли категорию
  if (benefits) {
    parts.push(`❓ *Проблема:* ${benefits.problem}`);
    parts.push(`✅ *Рішення:* ${benefits.benefit}`);
    parts.push(`🎯 *Де знадобиться:* ${benefits.useCase}`);
    parts.push('');
  }
  
  parts.push(`💰 *Ціна: ${product.price} грн*`);
  parts.push('');
  parts.push('👇 *Замовити:* тисни кнопку → бот напише в особисті');
  
  return parts.join('\n');
}

